const cache = new Map();
function verseText(file, chapter, verse) {
  if (!cache.has(file)) cache.set(file, JSON.parse(readFileSync(join(jsonDir, `${file}.json`), 'utf8')));
  const parts = cache
    .get(file)
    .filter((n) => n.chapterNumber === chapter && n.verseNumber === verse && typeof n.value === 'string')
    .map((n) => n.value);
  const text = parts.join(' ').replace(/\s+/g, ' ').trim();
  if (!text) throw new Error(`Verse not found: ${file} ${chapter}:${verse}`);
  return text;
}

const rows = CURATED.map(([book, file, chapter, verse, primary, secondary]) => ({
  id: `web-${file}-${chapter}-${verse}`,
  book,
  chapter,
  verse,
  text: verseText(file, chapter, verse),
  translation: 'WEB',
  primary_emotion_tag: primary,
  secondary_tags: secondary.join(','),
}));

const out = `// GENERATED by scripts/build-scripture-seed.mjs. Do not edit by hand.
// Source: World English Bible (public domain), https://ebible.org/web/
import type { ScriptureRow } from '../types';

export const SCRIPTURE_SEED: ScriptureRow[] = ${JSON.stringify(rows, null, 2)};
`;
